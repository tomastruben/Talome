import { mkdir, writeFile } from 'node:fs/promises';
import * as icons from '@hugeicons/core-free-icons';

// App identity artwork belongs in launchers; classic navigation keeps the same glyphs.
// Solid, opaque surfaces preserve contrast on both light and dark desktops.
const apps = [
  ['files', '/dashboard/files', 'HardDriveIcon', '#287DA8'],
  ['media', '/dashboard/media', 'Film01Icon', '#9960A8'],
  ['assistant', '/dashboard/assistant', 'Message01Icon', '#357F73'],
  ['terminal', '/dashboard/terminal', 'ComputerTerminal01Icon', '#343D49'],
  ['share', '/dashboard/share', 'Share04Icon', '#387DB2'],
  ['settings', '/dashboard/settings', 'Settings01Icon', '#626C79'],
  ['audiobooks', '/dashboard/audiobooks', 'BookOpen01Icon', '#A56838'],
  ['services', '/dashboard/containers', 'Package01Icon', '#5972AA'],
  ['app-store', '/dashboard/apps', 'DownloadSquare01Icon', '#387DA0'],
  ['automations', '/dashboard/automations', 'FlashIcon', '#946E28'],
  ['backups', '/dashboard/backups', 'ArchiveIcon', '#56816C'],
  ['intelligence', '/dashboard/intelligence', 'AiMagicIcon', '#7965A3'],
  ['launchpad', null, 'StartUp02Icon', '#546B86'],
];
const out = new URL('../public/app-icons/', import.meta.url);
await mkdir(out, { recursive: true });
const escape = (value) => String(value).replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;');
const attribute = (name) => name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
for (const [id, , iconName, color] of apps) {
  const glyph = icons[iconName];
  if (!glyph) throw new Error(`Unknown Hugeicons glyph: ${iconName}`);
  const shapes = glyph.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([key]) => key !== 'key').map(([key, value]) => `${attribute(key)}="${escape(value)}"`).join(' ')}/>`).join('');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 64 64"><rect x="1" y="1" width="62" height="62" rx="15" fill="${color}"/><rect x="1.5" y="1.5" width="61" height="61" rx="14.5" fill="none" stroke="#fff" stroke-opacity=".18"/><g transform="translate(14 14) scale(1.5)" fill="none" color="#fff" stroke-linecap="round" stroke-linejoin="round">${shapes}</g></svg>\n`;
  await writeFile(new URL(`${id}.svg`, out), svg);
}
const entries = apps.filter(([, route]) => route).map(([id, route]) => `  "${route}": "/app-icons/${id}.svg",`).join('\n');
await writeFile(new URL('../src/lib/desktop-app-artwork.ts', import.meta.url), `// Generated by scripts/generate-desktop-icons.mjs.\nconst artwork: Readonly<Record<string, string>> = {\n${entries}\n};\n\n/** Exact Talome routes only: installed apps retain their own brand artwork. */\nexport function desktopAppArtwork(url: string): string | undefined {\n  return artwork[url];\n}\n`);
